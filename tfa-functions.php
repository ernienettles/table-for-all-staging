// Google Fonts
function tfa_enqueue_fonts() {
    wp_enqueue_style(
        'tfa-google-fonts',
        'https://fonts.googleapis.com/css2?family=Playfair+Display:ital,wght@0,400;0,600;0,700;1,400&family=Inter:wght@300;400;500;600;700&display=swap',
        array(),
        null
    );
}
add_action( 'wp_enqueue_scripts', 'tfa_enqueue_fonts' );

// Enqueue child theme stylesheet
function tfa_enqueue_styles() {
    wp_enqueue_style(
        'tfa-style',
        get_stylesheet_uri(),
        array( 'generatepress-style' ),
        wp_get_theme()->get('Version')
    );
}
add_action( 'wp_enqueue_scripts', 'tfa_enqueue_styles', 20 );

// Custom Logo Setup
add_theme_support( 'custom-logo', array(
    'height' => 100,
    'width' => 300,
    'flex-height' => true,
) );

// Title Tag
add_theme_support( 'title-tag' );

// Featured Image
add_theme_support( 'post-thumbnails' );

// Register Menus
function tfa_register_menus() {
    register_nav_menus( array(
        'primary' => 'Primary Menu',
        'footer'  => 'Footer Menu',
    ) );
}
add_action( 'init', 'tfa_register_menus' );

